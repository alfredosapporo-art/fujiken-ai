@app.route("/chat", methods=["POST"])
def chat():
    data = request.get_json()
    user_message = data.get("message", "").strip()
    history = data.get("history", [])

    if not user_message:
        return jsonify({"error": "メッセージが空です"}), 400

    # ① まずGroqで試みる（高速・安定）
    if groq_client:
        try:
            messages = [{"role": "system", "content": SYSTEM_PROMPT}]
            for msg in history:
                messages.append({"role": msg["role"], "content": msg["content"]})
            messages.append({"role": "user", "content": user_message})

            response = groq_client.chat.completions.create(
                model="llama-3.3-70b-versatile",
                messages=messages,
                temperature=0.8,
                max_tokens=1024,
            )
            print("使用モデル: Groq / llama-3.3-70b-versatile")
            return jsonify({"response": response.choices[0].message.content})
        except Exception as e:
            print(f"Groqエラー: {e}")

    # ② GroqがだめならGeminiで試みる（フォールバック）
    if gemini_client:
        contents = []
        for msg in history:
            role = "user" if msg["role"] == "user" else "model"
            contents.append(types.Content(role=role, parts=[types.Part(text=msg["content"])]))
        contents.append(types.Content(role="user", parts=[types.Part(text=user_message)]))

        for model_name in ["models/gemini-2.5-flash", "models/gemini-2.0-flash-lite"]:
            for attempt in range(2):
                try:
                    response = gemini_client.models.generate_content(
                        model=model_name,
                        contents=contents,
                        config=types.GenerateContentConfig(
                            system_instruction=SYSTEM_PROMPT,
                            temperature=0.8,
                        )
                    )
                    print(f"使用モデル: Gemini / {model_name}")
                    return jsonify({"response": response.text})
                except Exception as e:
                    print(f"Geminiエラー ({model_name}): {e}")
                    time.sleep(2)

    return jsonify({"error": "応答できませんでした"}), 500

